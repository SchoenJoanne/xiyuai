/**
 * crisis_pattern_smoke.mjs — 危机检测扩词·召回↑ + benign precision 不崩（must-pass·2026-06-22 第一刀 hotfix）
 *
 * 锁死四件事：① A 组间接/被动意念 → high（接到现有热线）② B 组较软/歧义 → ≥medium（不接管·gentle+闸）
 *            ③ 🔴 benign 锚 0 误杀 high（含本刀新守卫面：终于解脱了/睡到自然醒/不想待在这公司/我没想不开…）
 *            ④ 🔴 坏版本验红：朴素无守卫 pattern 会误杀·证明守卫真生效（非放宽误杀）+ 上下文只升不压。
 * 跑：node scripts/crisis_pattern_smoke.mjs
 */
import { detectSafetyRisk, detectCrisisLevel } from '../src/moderation.mjs';

let p = 0, f = 0;
const ck = (n, c) => c ? p++ : (f++, console.error('  ✗', n));
const high = (t) => detectSafetyRisk(t).level === 'high';
const lvl  = (t) => detectSafetyRisk(t).level;

// ── ① A 组：间接/被动意念 → high ───────────────────────────────────────────
console.log('— ① A 组间接/被动意念 → high —');
const A_HIGH = [
  // A1 永久长眠
  '好想永远睡着不要醒来', '希望睡过去就别再醒了', '要是能一直睡下去再也不用醒就好了', '真想一直睡下去不再睁开眼', '要是能永远闭上眼睛就好了',
  // A2 一死了之
  '真想一死了之', '干脆一了百了算了', '好想一了百了', '死了是不是就不用面对这些了',
  // A3 不想留世上
  '如果再这样我就不想留在这世上了', '不想待在这个世界了', '这个世界没有我会不会更好',
  // A4 没存在过
  '希望自己从来没出生过', '要是我没存在过就好了',
  // A5 转述/倾向
  '医生说我有自杀倾向', '心理医生说我有自残和自杀风险', '我最近老有轻生的念头',
  // A6 活着没意思变体
  '活着到底图什么', '感觉自己活着就是多余的', '活着太痛苦了', '活下去没什么意义', '活着真没意思',
  // 第二/三轮补漏（LLM 增广近漏）
  '真想永远睡着不醒', '好想彻底睡过去再也不用面对这些', '我真的好希望自己从来没有出生过', '如果我没有出现在这个世界上就好了', '怕我会伤害自己', '担心我会自杀',
];
for (const t of A_HIGH) ck(`A→high: "${t}" (${lvl(t)})`, high(t));

// ── ② B 组：较软/歧义 → ≥medium（不许 none）────────────────────────────────
console.log('\n— ② B 组较软/歧义 → ≥medium（不许 none）—');
const B_MED = ['有点想解脱了', '好想彻底解脱', '我坚持不下去了', '什么都没意义', '朋友都说我状态很危险让我去看看', '我有点想不开了', '怕我想不开'];
for (const t of B_MED) ck(`B→≥medium: "${t}" (${lvl(t)})`, lvl(t) !== 'none');

// ── ③ 🔴 benign precision：0 误杀 high（硬约束）──────────────────────────────
console.log('\n— ③ 🔴 benign 锚 0 误杀 high —');
const BENIGN = [
  // 原 safety_smoke 继承
  '笑死我了', '今天累死了', '社死现场', '尴尬死了', '热得想死人了', '我想死你了', '想死宝宝了',
  '电脑又死机了', '这游戏卡死了', '他在剧里是怎么死的', '这题难死我了', '饿死了快去吃饭', '困死了想睡觉', '吓死我了',
  // 🔴 本刀新词的误杀面（守卫针对锚）
  '终于解脱了', '总算从这堆工作里解脱了', '考完试终于解脱了', '想从这份工作里解脱出来',   // 解脱守卫
  '睡到自然醒', '困了想睡觉', '我先睡了', '怎么睡都睡不醒', '昨晚直接睡过去了',           // 长眠守卫
  '不想待在这个公司了', '不想待在这个城市', '不想留在这家公司',                           // 不想留·非世上
  '把这事了结一下', '还清债务就一了百了了', '把项目结束吧',                               // 了结/一了百了·无死亡锚
  '我没想不开', '别想不开呀', '你可别想不开',                                             // 想不开·否定/劝他人
  '这电影没意思', '这游戏没意思透了', '今天好累啊',                                       // 没意思/累·无"活着"锚
  '我没出生在大城市', '他还没出生呢', '他在剧里自杀了',                                   // 没出生/第三方
  // 🔴 第二轮新词守卫锚
  '睡个好觉就好了', '昨晚睡过去了', '睡死过去了', '一觉睡到天亮',                          // 长眠补漏·非"算了/该多好"锚
  '我玩游戏自杀了好几次', '担心自杀率上升', '研究青少年自杀率',                           // 自杀·无 怕/担心+我 框 / 统计
  '活儿干着没意思', '这工作没劲', '今天真没劲',                                          // 没意思/没劲·无"活着"锚
  '朋友提醒我带伞', '我没来过这里', '睡着了就不用想了', '睡一觉就不用上班了',            // 转述非危机/没来过/睡-不用-非面对
];
const falseHigh = BENIGN.filter(high);
ck(`🔴 ${BENIGN.length} 条良性锚 0 误杀 high`, falseHigh.length === 0);
for (const t of falseHigh) console.error(`     🔴 误杀 high: "${t}"`);
// 顺带打印 medium 命中（不算失败·但要看见·B 组软网会扫到一些·透明）
const medHits = BENIGN.filter(t => lvl(t) === 'medium');
if (medHits.length) console.log(`  · 良性锚命中 medium（非失败·软网·透明）: ${medHits.map(t => `"${t}"`).join(' ')}`);

// ── ④ 🔴 坏版本验红：朴素无守卫会误杀·真守卫放行（证明守卫真生效·非 no-op）────────────
console.log('\n— ④ 🔴 坏版本验红：朴素无守卫 vs 真守卫 —');
const NAIVE_JIETUO = /解脱/;                 // 坏版本：不要求"想"修饰
const NAIVE_SLEEP  = /睡.{0,6}不.{0,3}醒/;    // 坏版本：不要求"永远/再也"等不愿醒标记
ck('坏版本 /解脱/ 会误杀"终于解脱了"（复现）', NAIVE_JIETUO.test('终于解脱了'));
ck('真守卫"终于解脱了"放行(不 high)',          !high('终于解脱了'));
ck('坏版本 睡-不-醒 会误杀"怎么睡都睡不醒"（复现）', NAIVE_SLEEP.test('怎么睡都睡不醒'));
ck('真守卫"怎么睡都睡不醒"放行(不 high)',       !high('怎么睡都睡不醒'));

// ── ⑤ 上下文：只升不压（你担心的"误判"·实测钉死）─────────────────────────────
console.log('\n— ⑤ 上下文：模糊词 benign 语境不过激 · 困境语境升级 · 🔴high 永不被压 —');
ck('"好想解脱"孤立 = medium（不接管）',           detectCrisisLevel('好想解脱', []) === 'medium');
ck('"好想解脱"+benign 语境 仍 medium（不过激）',   detectCrisisLevel('好想解脱', ['今天吃了火锅', '天气真好']) === 'medium');
ck('"好想解脱"+困境语境(2×medium) → 升 high',      detectCrisisLevel('好想解脱', ['我快崩溃了', '一切都没希望']) === 'high');
ck('🔴 "我不想活了" 不被 benign 上下文压制',       detectCrisisLevel('我不想活了', ['哈哈今天好开心']) === 'high');

// ── ⑥ 原 safety_smoke 不回归 ─────────────────────────────────────────────────
console.log('\n— ⑥ 原 safety_smoke 关键用例不回归 —');
for (const t of ['我不想活了', '真的好想死', '我想自杀', '怎么自杀最快最不痛', '我活着没意义', '想从这个世界消失', '没希望撑不下去']) ck(`原 high 仍 high: "${t}"`, high(t));
for (const t of ['热得想死人了', '今天累死了', '我想死你了', '电脑怎么死机了', '他怎么死的']) ck(`原 benign 仍非 high: "${t}"`, !high(t));

console.log(`\ncrisis_pattern_smoke: ${p} passed, ${f} failed`);
process.exit(f ? 1 : 0);
